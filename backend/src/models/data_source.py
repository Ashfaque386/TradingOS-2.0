"""Where the numbers behind a record came from.

A backtest run, a paper fill, a live trade and a post-trade review all report figures
(a Sharpe ratio, a win rate, a P&L) -- and nothing used to record whether those figures
rested on real market data or on data this system generated itself. Paper trading falls
back to a random-walk tick feed when no broker is configured, fills are walked through a
synthetic order book, and a backtest takes whatever bars its caller posts. A reader (or
an LLM, which receives the post-trade review's commentary in its prompt) could not tell a
measured result from a simulated one. `data_source` on those records says which.

`DataSource.SUPPLIED` is the honest label for input this system did not produce and cannot
vouch for: bars posted by a caller, a price typed in by an operator.
"""

from collections.abc import Iterable


class DataSource:
    """Plain string constants, like `BacktestStatus`: the column is a String with a CHECK
    constraint (`CHECK_SQL`), the same small-fixed-set choice the other status columns make."""

    REAL = "real"  # taken from the market: a live broker quote, a real execution
    SYNTHETIC = "synthetic"  # generated by this system: the mock tick walk, a fake provider
    SUPPLIED = "supplied"  # provided by the caller/operator; this system cannot vouch for it
    MIXED = "mixed"  # built from more than one of the above
    UNKNOWN = "unknown"  # not recorded (rows from before this existed) or not known

    ALL = (REAL, SYNTHETIC, SUPPLIED, MIXED, UNKNOWN)


CHECK_SQL = "data_source IN ('real','synthetic','supplied','mixed','unknown')"


def combine(sources: Iterable[str]) -> str:
    """The provenance of something built from several inputs. All the same: that. Any part
    `unknown`: `unknown` -- one input nobody can vouch for taints the whole, and saying "mixed"
    would claim a knowledge of the parts that does not exist. Otherwise: `mixed`. No inputs:
    `unknown`."""
    distinct = set(sources)
    if not distinct or DataSource.UNKNOWN in distinct:
        return DataSource.UNKNOWN
    if len(distinct) == 1:
        return next(iter(distinct))
    return DataSource.MIXED


_NOTES = {
    DataSource.REAL: "",
    DataSource.SYNTHETIC: (
        " Data: synthetic -- generated by this system, not taken from the market; "
        "do not read these figures as real performance."
    ),
    DataSource.SUPPLIED: (
        " Data: supplied by an operator or caller; this system cannot vouch for it."
    ),
    DataSource.MIXED: (
        " Data: partly synthetic (for example prices walked through a simulated order "
        "book); do not read these figures as real performance."
    ),
    DataSource.UNKNOWN: " Data: provenance was not recorded for these records.",
}


def provenance_note(source: str) -> str:
    """A sentence to append to a human- or LLM-facing summary so the reader is told what the
    figures rest on. Empty for real data: nothing to caveat."""
    return _NOTES.get(source, _NOTES[DataSource.UNKNOWN])
