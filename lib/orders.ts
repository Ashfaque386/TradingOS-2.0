/**
 * What the Orders & Trades page decides, kept free of React so a logic spec can drive it: which
 * statuses exist and how they read, what a price rests on, what to say about a position nobody is
 * watching, and the request for what is on screen.
 */
import type { LiveOrderDto, OrdersQuery, PositionByStrategy, UnifiedExecution } from './api'

/** Every status an execution can have: a paper fill is filled or partial; a live trade starts
 * pending confirmation and ends filled, rejected, cancelled or failed. */
export const EXECUTION_STATUSES = ['filled', 'partial', 'pending_confirmation', 'rejected', 'cancelled', 'failed'] as const

/** Every status a live order intent can have (the backend's CHECK vocabulary). */
export const INTENT_STATUSES = [
  'generated',
  'capped',
  'pending_approval',
  'approved',
  'submitted',
  'rejected',
  'expired',
  'failed',
] as const

export const statusLabel = (status: string): string => status.replace(/_/g, ' ')

export type Tone = 'good' | 'warn' | 'bad' | 'neutral'

/** How a status should look: finished well, still open, or not done. */
export function statusTone(status: string): Tone {
  switch (status) {
    case 'filled':
    case 'submitted':
    case 'approved':
      return 'good'
    case 'partial':
    case 'pending_confirmation':
    case 'pending_approval':
    case 'generated':
    case 'capped':
      return 'warn'
    case 'rejected':
    case 'cancelled':
    case 'failed':
    case 'expired':
      return 'bad'
    default:
      return 'neutral'
  }
}

export type SourceNote = { label: string; caution: boolean; explanation: string }

/** What a price rests on, in words. Anything but a real market price is marked as a caution, so a fill
 * on the mock tick walk never reads the same as one on a broker's quote. */
export function sourceNote(dataSource: string): SourceNote {
  switch (dataSource) {
    case 'real':
      return { label: 'Real', caution: false, explanation: 'Taken from the market: a broker’s quote or a real execution.' }
    case 'mixed':
      return {
        label: 'Mixed',
        caution: true,
        explanation: 'Real prices, but the fill was worked out against a simulated order book.',
      }
    case 'synthetic':
      return { label: 'Simulated', caution: true, explanation: 'Generated by this system: the mock tick walk or a fake provider.' }
    case 'supplied':
      return { label: 'Supplied', caution: true, explanation: 'Typed in or posted by a person; this system cannot vouch for it.' }
    default:
      return { label: 'Not recorded', caution: true, explanation: 'The source of this price was not recorded.' }
  }
}

export type OrdersFilter = {
  mode: 'both' | 'paper' | 'live'
  status: string
  symbol: string
  strategyId: string
}

export const NO_ORDERS_FILTER: OrdersFilter = { mode: 'both', status: '', symbol: '', strategyId: '' }

export const ordersFiltered = (filter: OrdersFilter): boolean =>
  filter.mode !== 'both' || filter.status !== '' || filter.symbol.trim() !== '' || filter.strategyId !== ''

/** The request for what is on screen: empty boxes are left out and the symbol is trimmed. */
export function ordersQuery(filter: OrdersFilter, page: number, size: number): OrdersQuery {
  const query: OrdersQuery = { mode: filter.mode, limit: size, offset: (Math.max(1, page) - 1) * size }
  if (filter.status) query.status = filter.status
  if (filter.symbol.trim()) query.symbol = filter.symbol.trim()
  if (filter.strategyId) query.strategyId = filter.strategyId
  return query
}

/** What a position's profit figure is: both modes report it before brokerage, taxes and charges. */
export const PNL_CAPTION = 'realised profit and loss, before costs'

/** A position that something is watching says nothing; one that nothing is watching says so. */
export function positionNote(position: PositionByStrategy): string | null {
  if (position.managed) return null
  return 'Not watched: its subscription is switched off, so no stop-loss is looking at it and no signal will close it.'
}

export const positionKey = (p: PositionByStrategy): string => `${p.mode}-${p.strategy_id}-${p.symbol}`

/** Why a live order failed, or nothing if it did not. */
export function failureLine(order: LiveOrderDto): string | null {
  if (order.status !== 'failed') return null
  return order.failure_reason?.trim() ? order.failure_reason.trim() : 'The broker refused it and gave no reason.'
}

/** How a signed profit or loss reads: `+₹1,250.00`, `-₹300.50`, `₹0.00`. */
export function formatPnl(value: number): string {
  const body = `₹${Math.abs(value).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
  if (value > 0) return `+${body}`
  if (value < 0) return `-${body}`
  return body
}

/** A price or a cost in rupees, or a dash when there is none. */
export function formatRupees(value: number | null | undefined): string {
  if (value === null || value === undefined || Number.isNaN(value)) return '—'
  return `₹${value.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

/** What a ledger row is about, in one line, for the "audit trail" link and for screen readers. */
export function describeExecution(row: UnifiedExecution): string {
  return `${row.side.toUpperCase()} ${row.quantity} ${row.symbol} (${row.mode}, ${statusLabel(row.status)})`
}
